"""Blackbox checks that the gateway route ownership page matches the mounted gateway app.

Governing ADRs: ADR-0015 (the gateway is thin and forwards the caller's token), ADR-0001 (the
owner checks object permissions). The page is generated by
scripts/generate_gateway_route_ownership.py. These tests read the committed page, run the
generator in check mode, and compare the page rows with the public routes that the app mounts.
They use the public app object only.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

from fastapi.routing import APIRoute
from gateway_api.main import app
from starlette.routing import WebSocketRoute

REPO_ROOT = Path(__file__).resolve().parents[1]
PAGE = REPO_ROOT / "docs" / "reference" / "gateway-route-ownership.md"
GENERATOR = REPO_ROOT / "scripts" / "generate_gateway_route_ownership.py"
ROW = re.compile(
    r"^\| (GET|POST|PUT|PATCH|DELETE|WS) \| `([^`]+)` \| ([^|]+?) \| (proxy|relay|local) \| `[^`]+` \|$",
    re.MULTILINE,
)


def _mounted_public_routes() -> set[tuple[str, str]]:
    """Return (method, path) for each API route and WebSocket route on the app."""
    found: set[tuple[str, str]] = set()
    for top in app.routes:
        if hasattr(top, "effective_route_contexts"):
            contexts = list(top.effective_route_contexts())
            for context in contexts:
                route = context.original_route
                path = context.path or context.starlette_route.path
                found |= _route_keys(route, path)
        else:
            found |= _route_keys(top, getattr(top, "path", ""))
    return found


def _route_keys(route: object, path: str) -> set[tuple[str, str]]:
    if isinstance(route, APIRoute):
        return {(method, path) for method in route.methods}
    if isinstance(route, WebSocketRoute):
        return {("WS", path)}
    return set()


def _page_rows() -> list[tuple[str, str, str, str]]:
    return [
        (method, path, owner.strip(), mode)
        for method, path, owner, mode in ROW.findall(PAGE.read_text(encoding="utf-8"))
    ]


def test_page_rows_match_the_mounted_public_routes() -> None:
    page_keys = {(method, path) for method, path, _, _ in _page_rows()}
    mounted = _mounted_public_routes()

    assert mounted, "the gateway app must mount public routes"
    assert page_keys - mounted == set(), "page rows with no mounted route"
    assert mounted - page_keys == set(), "mounted routes with no page row"


def test_every_row_names_an_owner_and_a_mode() -> None:
    rows = _page_rows()

    assert rows, "the ownership page has no rows"
    assert all(owner for _, _, owner, _ in rows)
    assert {mode for _, _, _, mode in rows} <= {"proxy", "relay", "local"}


def test_page_is_current_with_the_generator() -> None:
    result = subprocess.run(
        [sys.executable, str(GENERATOR), "--check"],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        timeout=300,
        check=False,
    )

    assert result.returncode == 0, result.stdout + result.stderr
