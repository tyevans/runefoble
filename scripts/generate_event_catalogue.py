#!/usr/bin/env python3
"""Generate the event identifier catalogue from the runefoble_events registry.

The catalogue is written to docs/reference/event-identifiers.md. Run it with
`uv run python scripts/generate_event_catalogue.py`. Pass `--check` to exit
with status 1 when the committed catalogue differs from the code.
"""

import argparse
import importlib
import pkgutil
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
CATALOGUE_PATH = REPO_ROOT / "docs" / "reference" / "event-identifiers.md"
IDENTIFIER_RULE = re.compile(r"^runefoble\.events\.[a-z][a-z0-9_]*\.[a-z][a-z0-9_]*$")

PREAMBLE = """# Reference: Event Identifiers

<!-- Generated by scripts/generate_event_catalogue.py. Do not edit by hand. -->

This table lists every registered domain event. The identifier column is the
`event_type` that each event carries on the wire. The value comes from
`event_type_name()` in `eventsource-py`.

## Identifier rule

Every identifier has this form:

`runefoble.events.<bc>.<snake_case>`

- `<bc>` names the owning bounded context or domain.
- `<snake_case>` names the event in lower case. Words are separated by underscores.
- An identifier never uses a class name. A retired identifier resolves to no event.
  The platform keeps no alias for a retired identifier.

A class sets its identifier in two places. The `@register_event("...")` decorator
registers the identifier. The class field `event_type` sets the value that the
event carries. Both must hold the same value.

CloudEvents exports (`to_cloudevent_dict()`) lower-case the identifier.
"""


def load_registered_classes() -> list[type]:
    """Import every runefoble_events module and return the registered event classes."""
    import runefoble_events
    from eventsource.domain.event_registry import default_registry

    for module in pkgutil.walk_packages(runefoble_events.__path__, runefoble_events.__name__ + "."):
        importlib.import_module(module.name)
    return sorted(set(default_registry.list_classes()), key=lambda cls: cls.__name__)


def catalogue_rows(classes: list[type]) -> list[tuple[str, str, str]]:
    """Return (identifier, class name, module) rows sorted by identifier.

    Raises ValueError when two classes share one identifier, because the
    catalogue must map each identifier to exactly one class.
    """
    seen: dict[str, str] = {}
    for cls in classes:
        identifier = cls.event_type_name()
        if not IDENTIFIER_RULE.match(identifier):
            raise ValueError(
                f"Event identifier {identifier!r} of {cls.__name__} breaks the rule "
                "runefoble.events.<bc>.<snake_case>"
            )
        if identifier in seen:
            raise ValueError(
                f"Event identifier {identifier!r} is used by both {seen[identifier]} and {cls.__name__}"
            )
        seen[identifier] = cls.__name__
    rows = [(cls.event_type_name(), cls.__name__, cls.__module__) for cls in classes]
    return sorted(rows)


def render_catalogue() -> str:
    """Return the full text of the event identifier catalogue page."""
    rows = catalogue_rows(load_registered_classes())
    lines = [PREAMBLE, "| Event identifier | Class | Module |", "|---|---|---|"]
    lines.extend(f"| `{identifier}` | `{name}` | `{module}` |" for identifier, name, module in rows)
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail when the committed catalogue differs from the registry.",
    )
    args = parser.parse_args(argv)

    rendered = render_catalogue()
    if args.check:
        committed = CATALOGUE_PATH.read_text(encoding="utf-8") if CATALOGUE_PATH.exists() else ""
        if committed != rendered:
            print(
                f"{CATALOGUE_PATH} is stale. Run scripts/generate_event_catalogue.py.",
                file=sys.stderr,
            )
            return 1
        print(f"{CATALOGUE_PATH} is current.")
        return 0

    CATALOGUE_PATH.write_text(rendered, encoding="utf-8")
    print(f"Wrote {CATALOGUE_PATH}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
